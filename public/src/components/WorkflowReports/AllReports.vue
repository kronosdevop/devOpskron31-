<script>
import { format_Date } from "@/JsonFiles/DateFormate.js";
import { list_all_reports } from "@/graphql/queries.js";
import { API, graphqlOperation } from "aws-amplify";
import axios from "axios";
const FileSaver = require("file-saver");

export default {
  props:{
      globalSearch:{
        type:String,
        default :"ALL"
      }
  },
  data() {
    return {
      search: "",
      currentPage: 1,
      itemsPerPage: 20,
      tableLoading: false,
      height: 0,
      tableData: [],
      headers: [
        { title: "Workflow Name", key: "report_name", sortable: false },
        { title: "Form Date", key: "report_from_date", sortable: false },
        { title: "To Date", key: "report_to_date", sortable: false },
        { title: "Generated On", key: "report_created_on", sortable: false },
        { title: "Generated By", key: "report_created_by", sortable: false },
        { title: "Status", key: "report_generation_status", sortable: false },
        { title: "Actions", key: "actions", sortable: false },
      ],
    };
  },

  computed: {
     globalSearch(){
      this.currentPage = 1
    },
filteredItems() {
  if (!this.globalSearch || this.globalSearch.trim() === "") {
    return this.tableData;
  }

  const search = this.globalSearch.toLowerCase();

  return this.tableData.filter(row =>
    Object.values(row).some(val =>
      val &&
      String(val).toLowerCase().includes(search)
    )
  );
}
,
    paginatedItems() {
      const start = (this.currentPage - 1) * this.itemsPerPage;
      return this.filteredItems.slice(start, start + this.itemsPerPage);
    },
    pageCount() {
      return Math.ceil(this.filteredItems.length / this.itemsPerPage);
    },
    startItem() {
      return this.filteredItems.length === 0
        ? 0
        : (this.currentPage - 1) * this.itemsPerPage + 1;
    },
    endItem() {
      return Math.min(
        this.currentPage * this.itemsPerPage,
        this.filteredItems.length
      );
    },
    totalCount() {
      return this.filteredItems.length;
    },
    visiblePages() {
      const pages = [];
      const start = Math.max(1, this.currentPage - 2);
      const end = Math.min(this.pageCount, this.currentPage + 2);
      for (let i = start; i <= end; i++) {
        pages.push(i);
      }
      return pages;
    },
  },

  watch: {
  
    currentPage(newVal) {
      // When the page changes, scroll to top of table (optional)
      const table = document.querySelector(".modern-data-table");
      if (table) table.scrollIntoView({ behavior: "smooth", block: "start" });
    },
  },

  created() {
    this.height = window.innerHeight - 250;
    this.fetch_records();
  },

  methods: {
    fetch_value(val) {
      return format_Date(val);
    },

    async fetch_records() {
      this.tableLoading = true;
      const user = this.$store.getters.GetUserObj;

      try {
        const result = await API.graphql(
          graphqlOperation(list_all_reports, {
            input: {
              organization_id: user.organization.organization_id,
              report_type: "WORKFLOW",
            },
          })
        );

        const response = JSON.parse(result.data.list_all_reports);
        if (response.Status === "SUCCESS") {
          this.tableData = response.data || [];
        }
      } catch (error) {
        this.$store.commit("SetSnackbar", {
          SnackbarVmodel: true,
          SnackbarColor: "red",
          SnackbarText: error.errors?.[0]?.message || "Error fetching records",
          timeout: 5000,
          Top: true,
        });
      } finally {
        this.tableLoading = false;
      }
    },

    async download_item(item) {
      const fileName = `${item.report_name}.xlsx`;

      try {
        const response = await axios({
          url: item.report_url,
          method: "GET",
          responseType: "blob",
        });

        const blob = new Blob([response.data], {
          type: response.headers["content-type"],
        });

        FileSaver.saveAs(blob, fileName);
      } catch (err) {
        this.$store.commit("SetSnackbar", {
          SnackbarVmodel: true,
          SnackbarColor: "red",
          SnackbarText: "Download failed.",
          timeout: 4000,
          Top: true,
        });
      }
    },

    handleSortChange(value) {
      // Implement the logic to handle sort change
    },

    updatePageItems(value) {
      // Implement the logic to update page items
    },
  },
};
</script>

