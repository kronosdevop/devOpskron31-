                    ? "IN PROGRESS"
                    : "NO RECORDS"
                }}
              </span>
            </div>
          </template>

          <!-- Actions -->
          <template v-slot:[`item.actions`]="{ item }">
            <div class="d-flex align-center justify-center">
              <v-icon
                v-if="item.report_generation_status === 'COMPLETED'"
                @click="download_item(item)"
                color="primary"
                class="cursor-pointer"
                size="20"
              >
                mdi-download
              </v-icon>
