<template>
  <div>
    <v-card flat>
  
      <!-- Data Table -->
      <v-card-text class="pa-4">
        <v-data-table
          :height="height"
          :fixed-header="true"
          :search="globalSearch"
          :headers="headers"
          :items="filteredItems"
          :items-per-page="itemsPerPage"
          :page="currentPage"
          :server-items-length="totalCount"
          :loading="tableLoading"
          class="modern-data-table"
          density="comfortable"
          hover
          multi-sort
          hide-default-footer
          @update:sort-by="handleSortChange"
        >
          <template v-slot:no-data>
            <div class="text-center py-8">
              <!-- <v-icon size="64" color="grey lighten-1" class="mb-4"
                >mdi-file-document-outline</v-icon
              > -->
              <div class="text-h6 grey--text mb-2">No Reports Found</div>
              <div class="text-body-2 grey--text">
                Try adjusting your search criteria.
              </div>
            </div>
          </template>

          <template v-slot:loading>
            <div class="text-center py-8">
              <v-progress-circular
                indeterminate
                color="primary"
                size="32"
                class="mb-4"
              ></v-progress-circular>
              <div class="text-body-2 grey--text">Loading reports...</div>
            </div>
          </template>

          <!-- Workflow Name -->
          <template v-slot:[`item.report_name`]="{ item }">
            <div class="d-flex align-center">
              <!-- <v-icon size="20" color="primary" class="mr-3"
                >mdi-file-document</v-icon
              > -->
              <div>
                <div class="font-weight-medium text-body-2">
                  {{ item.report_name }}
                </div>
              </div>
            </div>
          </template>

          <!-- From Date -->
          <template v-slot:[`item.report_from_date`]="{ item }">
            <div class="d-flex align-center">
              <!-- <v-icon size="16" color="grey" class="mr-2"
                >mdi-calendar-start</v-icon
              > -->
              <span class="caption">{{
                fetch_value(item.report_from_date)
              }}</span>
            </div>
          </template>

          <!-- To Date -->
          <template v-slot:[`item.report_to_date`]="{ item }">
            <div class="d-flex align-center">
              <!-- <v-icon size="16" color="grey" class="mr-2"
                >mdi-calendar-end</v-icon
              > -->
              <span class="caption">{{
                fetch_value(item.report_to_date)
              }}</span>
            </div>
          </template>

          <!-- Generated On -->
          <template v-slot:[`item.report_created_on`]="{ item }">
            <div class="d-flex align-center">
              <!-- <v-icon size="16" color="grey" class="mr-2"
                >mdi-calendar-clock</v-icon
              > -->
              <span class="caption">{{
                fetch_value(item.report_created_on)
              }}</span>
            </div>
          </template>

          <!-- Generated By -->
          <template v-slot:[`item.report_created_by`]="{ item }">
            <div class="d-flex align-center">
              <!-- <v-icon size="16" color="primary" class="mr-2"
                >mdi-account</v-icon
              > -->
              <span class="caption">{{ item.report_created_by }}</span>
            </div>
          </template>

          <!-- Status -->
          <template v-slot:[`item.report_generation_status`]="{ item }">
            <div class="d-flex align-center">
              <v-icon
                size="16"
                class="mr-2"
                :color="
                  item.report_generation_status === 'COMPLETED'
                    ? 'green'
                    : item.report_generation_status === 'IN PROGRESS'
                    ? 'orange'
                    : 'red'
                "
              >
                {{
                  item.report_generation_status === "COMPLETED"
                    ? "mdi-check-circle"
