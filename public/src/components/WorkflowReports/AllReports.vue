                    ? "mdi-clock"
                    : "mdi-close-circle"
                }}
              </v-icon>
              <span
                :class="
                  item.report_generation_status === 'COMPLETED'
                    ? 'green--text'
                    : item.report_generation_status === 'IN PROGRESS'
                    ? 'orange--text'
                    : 'red--text'
                "
                class="caption"
              >
                {{
                  item.report_generation_status === "COMPLETED"
                    ? "COMPLETED"
